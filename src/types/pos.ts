/**
 * An incremental order ticket generated by sendToKitchen (KOT/BOT) or
 * voidOrderItem (VOID_KOT / VOID_BOT).  Stored on Order.tickets so every
 * device can see the full ticket history for a table session.
 */
export interface Ticket {
  id: string;
  orderId: string;
  tableId: string;
  tableName: string;
  ticketType: TicketType;
  /** Sequential counter per-order per-type: KOT #1, KOT #2, BOT #1, … */
  ticketNumber: number;
  items: TicketItem[];
  serverName: string;
  customerName?: string;
  createdAt: string;
  status: 'pending' | 'printed';
  /** For VOID tickets: reason for cancellation */
  voidReason?: string;
  /** For VOID tickets: who authorised the void */
  voidedBy?: string;
}

