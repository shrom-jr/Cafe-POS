  printStatus?: {
    kot?: 'pending' | 'printed';
    bot?: 'pending' | 'printed';
  };
  /** Firebase conflict-resolution metadata. */
  syncRevision?: number;
  syncMutationId?: string;
  /** Opaque reset generations acknowledged by this order lifecycle. */
  activeFloorResetGeneration?: string;
  salesHistoryResetGeneration?: string;
